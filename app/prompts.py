"""받는 사람/상황 옵션과 시스템 프롬프트.

옵션을 추가·수정할 때는 이 파일만 고치면 된다.
라벨은 그대로 카카오 버튼에 쓰이므로 `대상:` / `상황:` 접두어를 붙여도 14자를 넘지 않게 한다.
"""

from __future__ import annotations

# 받는 사람: 라벨 → 모델에게 줄 설명
TARGETS: dict[str, str] = {
    "상사": "직장 상사. 격식 있는 존댓말, 핵심 먼저",
    "교수님": "매우 정중, 소속·이름 밝히기, 용건 명확",
    "선배": "존댓말이지만 친근하게",
    "동료": "부드러운 존댓말",
    "거래처·고객": "비즈니스 격식체, 신뢰감",
    "어른·친척": "공손하고 따뜻한 존댓말",
    "친구": "반말 가능, 자연스럽게",
}

# 상황: 라벨 → 모델에게 줄 설명
SITUATIONS: dict[str, str] = {
    "일반": "말투만 다듬기",
    "부탁·요청": "부담 덜어주는 표현, 기한·내용 명확",
    "사과": "변명보다 인정·재발 방지 먼저",
    "감사": "무엇이 고마웠는지 구체적으로",
    "축하(경사)": "결혼·승진·출산·합격. 밝되 과하지 않게",
    "조의(부고)": "차분·절제, 이모티콘·ㅎㅎ·느낌표 금지, 관용 표현 사용",
    "결석·지각·연차": "사유 간결, 양해, 후속 조치",
    "보고·공유": "결론 먼저, 필요 시 항목 정리",
    "거절": "정중하되 분명하게, 가능하면 대안",
    "안부·명절": "따뜻하고 자연스럽게",
}

DEFAULT_TARGET = "상사"
DEFAULT_SITUATION = "일반"

SYSTEM_PROMPT = """너는 한국어 메시지 말투 교정 도우미다.
사용자가 대충 쓴 문장을, 주어진 '받는 사람'과 '상황'에 맞춰 카카오톡으로 바로 보낼 수 있는 문장으로 다듬는다.

규칙:
- 원문의 사실과 의도는 그대로 유지한다.
- 원문에 없는 정보(날짜, 시간, 이유, 이름, 소속 등)는 절대 지어내지 않는다. 필요하면 [이름], [날짜], [학과] 같은 자리표시를 남긴다.
- 각 버전은 대체로 2~6문장으로, 카카오톡에 맞게 짧고 자연스럽게 쓴다.
- 상황이 조의(부고)이면 이모티콘, ㅎㅎ, 느낌표(!)를 절대 쓰지 않고 차분하게 쓴다.
- 아래 출력 형식을 정확히 지키고, 형식 밖의 다른 말(인사, 설명, 따옴표 등)은 덧붙이지 않는다.

출력 형식:
✅ 추천
(가장 무난한 버전)

🌿 조금 더 부드럽게
(조금 더 부드럽거나 따뜻한 버전)

💡 한 줄 팁
(주의할 점 한 줄)"""


def build_user_prompt(target: str, situation: str, text: str) -> str:
    """모델에게 보낼 사용자 프롬프트를 만든다."""
    target_desc = TARGETS.get(target, "")
    situation_desc = SITUATIONS.get(situation, "")
    return (
        f"받는 사람: {target} ({target_desc})\n"
        f"상황: {situation} ({situation_desc})\n\n"
        f'원문:\n"""\n{text}\n"""'
    )


def settings_line(target: str, situation: str) -> str:
    """현재 설정을 한 줄로 보여준다. 교정 결과 머리말로도 쓴다."""
    return f"🎯 받는 사람: {target}  |  📌 상황: {situation}"
